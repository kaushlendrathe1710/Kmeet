export function getFreeBackgrounds(): BackgroundItem[] {
  return BACKGROUND_ITEMS.filter(item => !item.isPremium);
}

export function getPremiumBackgrounds(): BackgroundItem[] {
  return BACKGROUND_ITEMS.filter(item => item.isPremium);
}
